import { z } from "zod";

export const DeckPresentationSchema = z.object({
  meta: z.object({
    title: z.string().min(1),
    description: z.string().min(1),
    ogTitle: z.string().min(1),
    ogDescription: z.string().min(1),
  }),
  intro: z.object({
    eyebrow: z.string().min(1),
    title: z.string().min(1),
    highlight: z.string().min(1),
    description: z.string().min(1),
  }),
  theme: z.object({
    background: z.string().regex(/^#[\da-f]{3,8}$/i),
    surface: z.string().regex(/^#[\da-f]{3,8}$/i),
    panel: z.string().regex(/^#[\da-f]{3,8}$/i),
    border: z.string().regex(/^#[\da-f]{3,8}$/i),
    text: z.string().regex(/^#[\da-f]{3,8}$/i),
    muted: z.string().regex(/^#[\da-f]{3,8}$/i),
    dim: z.string().regex(/^#[\da-f]{3,8}$/i),
    accent: z.string().regex(/^#[\da-f]{3,8}$/i),
    accentBlue: z.string().regex(/^#[\da-f]{3,8}$/i),
    accentGreen: z.string().regex(/^#[\da-f]{3,8}$/i),
  }),
  ui: z.object({
    documentLabel: z.string().min(1),
    carouselLabel: z.string().min(1),
    shareLabel: z.string().min(1),
    printLabel: z.string().min(1),
    chooseSectionLabel: z.string().min(1),
    goToSectionLabel: z.string().min(1),
    previousSectionLabel: z.string().min(1),
    nextSectionLabel: z.string().min(1),
    documentAriaLabel: z.string().min(1),
    carouselAriaLabel: z.string().min(1),
    sectionCountLabel: z.string().min(1),
    linkCopiedNotice: z.string().min(1),
    copyFallbackNotice: z.string().min(1),
    shareErrorNotice: z.string().min(1),
    portfolioLabel: z.string().min(1),
    liveProductLabel: z.string().min(1),
    availableServicesLabel: z.string().min(1),
    illustrativeLabel: z.string().min(1),
    brandTagline: z.string().min(1),
    brandDescription: z.string().min(1),
    whatsappLabel: z.string().min(1),
    tabTitle: z.string().min(1),
    tabBadge: z.string().min(1),
    tabHint: z.string().min(1),
    tabHintTouch: z.string().min(1),
    tabPausedHint: z.string().min(1),
    featureDevelopmentLabel: z.string().min(1),
    emptyMessage: z.string().min(1),
  }),
  slides: z.array(z.object({
    id: z.string().min(1),
    kind: z.enum(["bookmyslot", "mossaic-labs", "mossaic-studio"]),
    navigationLabel: z.string().min(1).optional(),
    eyebrow: z.string().min(1),
    title: z.string().min(1),
    highlight: z.string().optional(),
    description: z.string().min(1),
    linkLabel: z.string().min(1).optional(),
    footer: z.string().min(1),
  })).min(1),
  narrative: z.object({
    dashboardTitle: z.string().min(1),
    dashboardHint: z.string().min(1),
    demoDisclaimer: z.string().min(1),
    demoMetrics: z.array(z.object({ value: z.string().min(1), label: z.string().min(1) })).min(1),
    pipelineTitle: z.string().min(1),
    pipelineProducts: z.array(z.object({
      productId: z.string().min(1),
      title: z.string().min(1),
      description: z.string().min(1),
    })).min(1),
    customServiceTitle: z.string().min(1),
    customServiceDescription: z.string().min(1),
    customServiceActionLabel: z.string().min(1),
    closingTitle: z.string().min(1),
    closingDescription: z.string().min(1),
  }),
  demoPatients: z.array(z.object({
    initials: z.string().min(1),
    name: z.string().min(1),
    id: z.string().min(1),
    age: z.string().min(1),
    gender: z.string().min(1),
    scheduled: z.string().min(1),
    reason: z.string().min(1),
    status: z.enum(["pending", "confirmed"]),
  })).min(1),
}).strict();
